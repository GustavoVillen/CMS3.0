def make_sku(motor, part):
    """Build a SKU: MOTOR-PARTNUMBER (sanitized)."""
    motor_short = motor.split()[0] if motor else "GEN"
    motor_short = re.sub(r"[^A-Z0-9]", "", motor_short.upper())[:4]
    part_clean = re.sub(r"[^A-Z0-9]", "", str(part).upper())[:20]
    return f"{motor_short}-{part_clean}"


def build_spares():
    sql = HEADER.format(title="Mercurio — Repuestos críticos")
    sql += tenant_resolver()
    sql += "\n  -- ── Insert spares per vessel (one row per vessel × spare). ────────────────\n"

    spares = DATA["spares"]
    seen = set()
    count = 0

    for sp in spares:
        motor = sp["motor"] or ""
        part  = sp["partNumber"] or ""
        name  = sp["name"] or ""
        if not part or not name:
            continue

        # Resolve which vessels this spare applies to
        vessels_for_spare = sp.get("vessels") or []
        if not vessels_for_spare:
            vessels_for_spare = MOTOR_VESSEL_MAP.get(motor.upper(), [])
        if not vessels_for_spare:
            continue

        sku = make_sku(motor, part)
        crit = sp.get("criticality") or "B"
        min_qty = sp.get("minQty") or 0

        for vc in vessels_for_spare:
            ident = (vc, sku)
            if ident in seen:
                continue
            seen.add(ident)
            sql += f"""  INSERT INTO "Spare" (id, "tenantId", "vesselCode", sku, name, "manufacturerPartNumber", manufacturer, criticality, unit, "currentStock", "minStock", "reorderPoint", status, "createdAt", "createdByUserId", "updatedAt", "updatedByUserId")
  VALUES (gen_random_uuid()::text, v_tenant_id, {sql_str(vc)}, {sql_str(sku)}, {sql_str(name)}, {sql_str(part)}, {sql_str(motor)}, '{crit}', 'UN', 0, {min_qty}, {min_qty}, 'ACTIVE', NOW(), v_user_id, NOW(), v_user_id)
  ON CONFLICT ("tenantId", "vesselCode", sku) DO NOTHING;
"""
            count += 1

    sql += f"\n  RAISE NOTICE 'Spares processed: ~{count} rows';\n"
    sql += "END $$;\n\nCOMMIT;\n"
    (OUT / "07-mercurio-spares.sql").write_text(sql, encoding="utf-8")
    print(f"  -> 07-mercurio-spares.sql  (~{count} spare-vessel rows)")


