def build_vessels_sql():
    # Use vessels from FLOTA + cross-reference certificates to capture YERUTI etc.
    vessels = {}
    for v in DATA["vessels"]:
        code = vessel_code_for(v["name"])
        if not code:
            continue
        vessels[code] = {
            "code":   code,
            "name":   v["name"],
            "type":   v.get("tipo"),
            "registration": v.get("matricula"),
        }

    # Add vessels from certificates not in flota
    cert_vessels = set()
    for c in DATA["certificates"]:
        cv = vessel_code_for(c["vessel"])
        if cv and cv not in vessels:
            cert_vessels.add((cv, c["vessel"]))
    for code, name in cert_vessels:
        vessels[code] = {"code": code, "name": name, "type": None, "registration": None}

    sql = HEADER.format(title="Mercurio — Vessels")
    sql += tenant_resolver()
    sql += "\n  -- ── Insert vessels (idempotent via @@unique [tenantId, code]) ─────────────\n"
    for code in sorted(vessels.keys()):
        v = vessels[code]
        sql += f"""  INSERT INTO "Vessel" (id, "tenantId", code, name, "vesselType", registration, status, "createdAt", "createdByUserId", "updatedAt", "updatedByUserId")
  VALUES (gen_random_uuid()::text, v_tenant_id, {sql_str(v['code'])}, {sql_str(v['name'])}, {sql_str(v['type'])}, {sql_str(v['registration'])}, 'ACTIVE', NOW(), v_user_id, NOW(), v_user_id)
  ON CONFLICT ("tenantId", code) DO NOTHING;
"""
    sql += "\n  RAISE NOTICE 'Vessels processed';\n"
    sql += "END $$;\n\n"
    sql += """SELECT COUNT(*) AS vessels_active
FROM "Vessel" v
JOIN "Tenant" t ON t.id = v."tenantId"
WHERE t.slug = 'mercurio' AND v.status = 'ACTIVE';

COMMIT;
"""
    (OUT / "00-mercurio-vessels.sql").write_text(sql, encoding="utf-8")
    print(f"  -> 00-mercurio-vessels.sql  ({len(vessels)} vessels)")
    return vessels


