def sql_str(s):
    """Quote string for SQL, handling None and escaping single quotes."""
    if s is None or s == "":
        return "NULL"
    s = str(s).replace("\x00", "").replace("\r", "")
    s = s.replace("'", "''")
    return f"'{s}'"


def sql_int(n):
    if n is None or n == "":
        return "NULL"
    try:
        return str(int(n))
    except (ValueError, TypeError):
        return "NULL"


def sql_float(n):
    if n is None or n == "":
        return "NULL"
    try:
        return str(float(n))
    except (ValueError, TypeError):
        return "NULL"


def sql_date(s):
    """Convert datestring to SQL date, or NULL if not parseable."""
    if not s:
        return "NULL"
    if isinstance(s, str):
        m = re.match(r"^(\d{4})-(\d{2})-(\d{2})", s)
        if m:
            return f"'{m.group(1)}-{m.group(2)}-{m.group(3)}'"
    return "NULL"


def normalize_text(s):
    if s is None:
        return ""
    return re.sub(r"\s+", " ", str(s).strip())


def vessel_code_for(name):
    """Convert display name to vessel code (uppercase, no spaces, special-cases)."""
    if not name:
        return None
    n = name.upper().strip()
    # Special cases
    if n == "DON CHICUETO":          return "DONCHI"
    if n == "DON CHICHUETO":         return "DONCHI"  # typo variant
    # Roman numeral suffix → arabic (cleaner)
    n = re.sub(r"\s+VIII\s*$", "8", n)
    n = re.sub(r"\s+VII\s*$",  "7", n)
    n = re.sub(r"\s+VI\s*$",   "6", n)
    n = re.sub(r"\s+IV\s*$",   "4", n)
    n = re.sub(r"\s+III\s*$",  "3", n)
    n = re.sub(r"\s+II\s*$",   "2", n)
    n = re.sub(r"\s+IX\s*$",   "9", n)
    n = re.sub(r"\s+X\s*$",    "10", n)
    n = re.sub(r"\s+V\s*$",    "5", n)
    n = re.sub(r"\s+I\s*$",    "1", n)
    return re.sub(r"\s+", "", n)


# ─────────────────────────────────────────────────────────────────────────────
# Header used in all SQL scripts (resolves tenant + user + helper functions)
# ─────────────────────────────────────────────────────────────────────────────
HEADER = """-- =============================================================================
-- {title}
-- =============================================================================
-- Generated by scripts/mercurio-import/build_sql.py
-- Tenant: Mercurio (resolved by slug or fallback via LATERE vessel)
-- Idempotent: re-running keeps a single row per (tenant, vesselCode, code)
-- =============================================================================

BEGIN;

DO $$
DECLARE
  v_tenant_id text;
  v_user_id   text;
"""


def tenant_resolver(extra_decls=""):
    """Returns the SQL block that resolves tenant + user."""
    return f"""{extra_decls}
BEGIN
  -- Resolve tenant: prefer slug 'mercurio', fallback via LATERE vessel
  SELECT id INTO v_tenant_id FROM "Tenant" WHERE slug = 'mercurio' LIMIT 1;
  IF v_tenant_id IS NULL THEN
    SELECT t.id INTO v_tenant_id
    FROM "Tenant" t
    JOIN "Vessel" v ON v."tenantId" = t.id
    WHERE v.code IN ('LATERE','DONCHI','DON CHICUETO')
    ORDER BY v."createdAt" ASC
    LIMIT 1;
  END IF;
  IF v_tenant_id IS NULL THEN
    RAISE EXCEPTION 'Tenant Mercurio not found (no slug match and no LATERE/DONCHI vessel)';
  END IF;

  SELECT m."userId" INTO v_user_id
  FROM "TenantMembership" m
  WHERE m."tenantId" = v_tenant_id AND m.role = 'TENANT_ADMIN'
  ORDER BY m."createdAt" ASC LIMIT 1;
  IF v_user_id IS NULL THEN
    SELECT m."userId" INTO v_user_id
    FROM "TenantMembership" m
    WHERE m."tenantId" = v_tenant_id
    ORDER BY m."createdAt" ASC LIMIT 1;
  END IF;
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'No member found for Mercurio tenant';
  END IF;
  RAISE NOTICE 'Tenant: %, User: %', v_tenant_id, v_user_id;
"""


