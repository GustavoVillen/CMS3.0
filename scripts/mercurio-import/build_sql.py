def system_asset_code(vessel_code, system_code):
    return f"{vessel_code}-SYS-{system_code}"


def write_assets_sql(label, vessels_with_systems, output_filename):
    """vessels_with_systems = dict[vessel_code] -> set of system_codes used."""
    sql = HEADER.format(title=label)
    sql += tenant_resolver()
    sql += "\n  -- ── Insert system assets (parents). Each is a 'bucket' with criticality + safety set.\n"
    for vc in sorted(vessels_with_systems.keys()):
        sql += f"\n  -- {vc}\n"
        for sc in sorted(vessels_with_systems[vc]):
            asset_code = system_asset_code(vc, sc)
            name       = SYSTEM_NAMES.get(sc, sc)
            crit, safe = SYSTEM_CRITICALITY.get(sc, ("B", False))
            sql += f"""  INSERT INTO "Asset" (id, "tenantId", "vesselCode", "assetCode", name, criticality, status, "isSafetyCritical", "trackDailyReport", "createdAt", "createdByUserId", "updatedAt", "updatedByUserId")
  VALUES (gen_random_uuid()::text, v_tenant_id, {sql_str(vc)}, {sql_str(asset_code)}, {sql_str(name)}, '{crit}', 'OPERATIONAL', {str(safe).lower()}, false, NOW(), v_user_id, NOW(), v_user_id)
  ON CONFLICT ("tenantId", "vesselCode", "assetCode") DO NOTHING;
"""

    sql += "\n  RAISE NOTICE 'System (parent) assets processed';\n"
    sql += "END $$;\n\nCOMMIT;\n"
    (OUT / output_filename).write_text(sql, encoding="utf-8")


def write_plans_sql(label, plans, output_filename):
    sql = HEADER.format(title=label)
    sql += tenant_resolver("  v_asset_id  text;\n  v_count     integer := 0;")
    sql += "\n  -- ── Insert MaintenancePlans grouped by (vessel, system, frequency, type) ──\n"

    by_vessel = defaultdict(list)
    for p in plans:
        by_vessel[p["vesselCode"]].append(p)

    for vc in sorted(by_vessel.keys()):
        sql += f"\n  -- ── Vessel {vc} ──\n"
        for p in by_vessel[vc]:
            sc = p["systemCode"]
            asset_code = system_asset_code(vc, sc)
            sys_label = SYSTEM_NAMES.get(sc, sc)
            kind = "Inspección" if p["isInspection"] else "Mantenimiento"
            title = f"[{sys_label}] {kind} {p['label']}"
            insp_suffix = "I" if p["isInspection"] else "M"
            task_code = f"{vc}-{sc}-{freq_code_short(p['trigger'], p['hours'], p['months'])}-{insp_suffix}"
            description = build_description(p)
            trigger_enum = "HOURS" if p["trigger"] == "HOURS" else "MONTHS"
            task_type    = "INSPECTION" if p["isInspection"] else "MAINTENANCE"

            sql += f"""  -- {title}
  SELECT id INTO v_asset_id FROM "Asset"
   WHERE "tenantId" = v_tenant_id AND "vesselCode" = {sql_str(vc)} AND "assetCode" = {sql_str(asset_code)} AND "deletedAt" IS NULL LIMIT 1;
  IF v_asset_id IS NOT NULL THEN
    INSERT INTO "MaintenancePlan" (
      id, "tenantId", "vesselCode", "assetId", "taskCode", title, description,
      "triggerType", "frequencyHours", "frequencyMonths", "taskType", status, "executionStatus",
      "createdAt", "createdByUserId", "updatedAt", "updatedByUserId"
    )
    VALUES (
      gen_random_uuid()::text, v_tenant_id, {sql_str(vc)}, v_asset_id, {sql_str(task_code)},
      {sql_str(title)}, {sql_str(description)},
      CAST({sql_str(trigger_enum)} AS "MaintenancePlanTrigger"),
      {sql_float(p["hours"])}, {sql_int(p["months"])},
      CAST({sql_str(task_type)} AS "TaskType"),
      CAST('ACTIVE' AS "MaintenancePlanStatus"),
      CAST('FUTURE' AS "ExecutionStatus"),
      NOW(), v_user_id, NOW(), v_user_id
    )
    ON CONFLICT ("tenantId", "vesselCode", "taskCode") DO NOTHING;
    v_count := v_count + 1;
  END IF;
"""

    sql += "\n  RAISE NOTICE 'MaintenancePlans processed: %', v_count;\n"
    sql += "END $$;\n\nCOMMIT;\n"
    (OUT / output_filename).write_text(sql, encoding="utf-8")


